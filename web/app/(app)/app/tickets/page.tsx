import type { Metadata } from "next";
import { createClient } from "@/lib/supabase/server";
import { getCachedTicketsByEmails } from "@/lib/automations/support-tickets/ticket-cache";
import { resolveUserIdentity } from "@/lib/automations/support-tickets/email-aliases";
import { EmptyTicketsState } from "@/components/app/empty-tickets-state";
import { TicketsErrorState } from "@/components/app/tickets-error-state";
import {
  TicketsBrowser,
  type TicketRow,
} from "@/components/app/tickets-browser";
import { getI18n } from "@/lib/i18n/server";
import { translateStatus } from "@/lib/i18n";
import { getUnreadTaskIds } from "@/lib/automations/support-tickets/notification-preferences";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Mijn tickets — MR Support",
};

/**
 * Bucket a granular ClickUp status into a user-facing filter group.
 * "Open" is the catch-all for every active status (anything that isn't rejected
 * or resolved), so any current or future status stays reachable.
 */
function groupOf(rawStatus: string): TicketRow["group"] {
  const s = rawStatus.toLowerCase();
  if (s === "resolved") return "resolved";
  if (s === "rejected") return "rejected";
  return "open";
}

export default async function TicketsPage() {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  // user is guaranteed non-null — layout.tsx already redirected if null

  // Resolve aliases + AD preferred language in one cached Graph call.
  // Filter emails sourced exclusively from the server session (TICK-07 / T-02-06),
  // expanded to all of the user's M365 aliases (email-aliases.ts).
  const { emails, preferredLocale } = await resolveUserIdentity(user!.email!);
  const { locale, dict } = await getI18n(preferredLocale);
  // Read from the local cache (mirrored from ClickUp via webhook), not live —
  // this is what makes the page fast (e.g. settings → tickets). See
  // ticket-cache.ts + clickup-cache-sync.ts.
  const result = await getCachedTicketsByEmails(emails, locale);

  if ("error" in result) {
    // DB unavailable — distinct error state (TICK-08 / T-02-08)
    return (
      <TicketsErrorState
        title={dict.tickets.error.title}
        body={dict.tickets.error.body}
      />
    );
  }

  if (result.tickets.length === 0) {
    return (
      <EmptyTicketsState
        title={dict.tickets.empty.title}
        body={dict.tickets.empty.body}
        cta={dict.tickets.empty.cta}
      />
    );
  }

  // Unread badge: determine which tickets have notifications newer than last-seen.
  // Fail-safe: getUnreadTaskIds returns empty Set on any error.
  const unreadIds = await getUnreadTaskIds(emails);

  // Titles are already localized from the translation cache (pre-generated by
  // clickup-cache-sync) — no Orq.ai call on render.
  const rows: TicketRow[] = result.tickets.map((t) => ({
    id: t.id,
    title: t.title,
    statusLabel: translateStatus(dict, t.rawStatus),
    statusColor: t.statusDisplay.color,
    group: groupOf(t.rawStatus),
    createdAtLabel: t.createdAt.toLocaleDateString("nl-NL"),
    hasUnread: unreadIds.has(t.id),
  }));

  return (
    <div>
      <h1 className="font-display text-xl font-semibold text-[var(--v7-text)] tracking-[-0.02em] mb-6">
        {dict.tickets.title}
      </h1>
      <TicketsBrowser tickets={rows} t={dict.tickets} />
    </div>
  );
}
